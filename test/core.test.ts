const MIN = 60_000;

describe("parseLluTimestamp", () => {
  test("US 12-hour UTC", () => {
    expect(parseLluTimestamp("11/24/2026 10:05:00 AM")).toBe(Date.UTC(2026, 10, 24, 10, 5));
    expect(parseLluTimestamp("11/24/2026 12:05:00 AM")).toBe(Date.UTC(2026, 10, 24, 0, 5));
    expect(parseLluTimestamp("11/24/2026 12:05:00 PM")).toBe(Date.UTC(2026, 10, 24, 12, 5));
    expect(parseLluTimestamp("1/2/2026 3:04:05 PM")).toBe(Date.UTC(2026, 0, 2, 15, 4, 5));
  });
  test("24-hour, ISO, epoch", () => {
    expect(parseLluTimestamp("11/24/2026 22:05:00")).toBe(Date.UTC(2026, 10, 24, 22, 5));
    expect(parseLluTimestamp("2026-11-24T10:05:00Z")).toBe(Date.UTC(2026, 10, 24, 10, 5));
    expect(parseLluTimestamp("2026-11-24T18:05:00+08:00")).toBe(Date.UTC(2026, 10, 24, 10, 5));
    expect(parseLluTimestamp("2026-11-24 10:05:00")).toBe(Date.UTC(2026, 10, 24, 10, 5));
    expect(parseLluTimestamp(1795000000)).toBe(1795000000000);
  });
  test("garbage", () => {
    expect(parseLluTimestamp("")).toBeNull();
    expect(parseLluTimestamp("yesterday")).toBeNull();
    expect(parseLluTimestamp(undefined)).toBeNull();
  });
});

describe("local timestamps", () => {
  test("split + order detection", () => {
    const a = splitLocalTimestamp("24-11-2026 22:05")!;
    const b = splitLocalTimestamp("03-11-2026 08:00")!;
    expect(detectDateOrder([a, b])).toBe("DMY");
    expect(detectDateOrder([splitLocalTimestamp("11-24-2026 10:05 PM")!])).toBe("MDY");
    expect(detectDateOrder([splitLocalTimestamp("2026/11/24 下午 10:05")!])).toBe("YMD");
    const p = splitLocalTimestamp("2026/11/24 下午 10:05")!;
    expect(partsToEpoch(p, "YMD", 480)).toBe(Date.UTC(2026, 10, 24, 14, 5));
  });
});

const META = "Glucose Data,Generated on,11-24-2026 09:00 UTC,Generated by,Someone\n";

describe("parseLibreViewCsv", () => {
  test("mg/dL, MDY, historic + scan, non-glucose rows skipped", () => {
    const csv =
      META +
      "Device,Serial Number,Device Timestamp,Record Type,Historic Glucose mg/dL,Scan Glucose mg/dL,Non-numeric Rapid-Acting Insulin\n" +
      "FreeStyle LibreLink,ABC,11-24-2026 08:00 AM,0,100,,\n" +
      "FreeStyle LibreLink,ABC,11-24-2026 08:15 AM,0,120,,\n" +
      "FreeStyle LibreLink,ABC,11-24-2026 08:20 AM,1,,130,\n" +
      'FreeStyle LibreLink,ABC,11-24-2026 08:30 AM,6,,,"note, with comma"\n';
    const r = parseLibreViewCsv(csv, 480);
    expect(r.unit).toBe("mg/dL");
    expect(r.dateOrder).toBe("MDY");
    expect(r.readings.map((x) => x.mgdl)).toEqual([100, 120, 130]);
    expect(r.readings[0]!.ts).toBe(Date.UTC(2026, 10, 24, 0, 0)); // 08:00 Taiwan
    expect(r.rowsSkipped).toBe(1);
  });

  test("mmol/L, DMY, columns in another order", () => {
    const csv =
      META +
      "Device,Serial Number,Record Type,Device Timestamp,Scan Glucose mmol/L,Historic Glucose mmol/L\n" +
      "X,1,0,25-11-2026 07:00,,5.5\r\n" +
      "X,1,0,25-11-2026 07:15,,7.0\r\n";
    const r = parseLibreViewCsv(csv, 0);
    expect(r.unit).toBe("mmol/L");
    expect(r.dateOrder).toBe("DMY");
    expect(r.readings.map((x) => x.mgdl)).toEqual([99.1, 126.1]);
    expect(r.readings[0]!.ts).toBe(Date.UTC(2026, 10, 25, 7, 0));
  });
});

describe("analyzeMeal", () => {
  const t0 = Date.UTC(2026, 10, 24, 4, 0);
  const now = t0 + 24 * 60 * MIN;
  // 15-minute curve: baseline 100, peak 160 at +45, back to ~100 by +120.
  const curve = [100, 100, 100, 130, 155, 160, 140, 120, 105, 100, 98, 98, 99, 100, 100];
  const pts = curve.map((mgdl, i) => ({ ts: t0 + (i - 2) * 15 * MIN, mgdl }));

  test("clean response", () => {
    const r = analyzeMeal(t0, pts, [], { now });
    expect(r.baseline).toBe(100);
    expect(r.peak).toBe(160);
    expect(r.minutesToPeak).toBe(45);
    expect(r.delta).toBe(60);
    expect(r.at2h).toBe(98);
    expect(r.minutesToReturn).toBe(90);
    expect(r.flags).toEqual([]);
    expect(r.confidence).toBe("high");
    // trapezoid sum of (y-100) per 15-min step: 0,30,55,60,40,20,5,0 → (0+30)/2+(30+55)/2+...
    expect(r.iauc).toBeCloseTo((15 + 42.5 + 57.5 + 50 + 30 + 12.5 + 2.5) * 0.25, 1);
  });

  test("gap lowers confidence", () => {
    const gappy = pts.filter((p) => p.ts < t0 + 30 * MIN || p.ts > t0 + 90 * MIN);
    const r = analyzeMeal(t0, gappy, [], { now });
    expect(r.flags).toContain("gap");
    expect(r.confidence).toBe("low");
  });

  test("overlapping meal lowers confidence", () => {
    const r = analyzeMeal(t0, pts, [t0, t0 + 60 * MIN], { now });
    expect(r.flags).toContain("overlap");
    expect(r.confidence).toBe("low");
  });

  test("no baseline / incomplete window", () => {
    const after = pts.filter((p) => p.ts > t0 + 20 * MIN);
    expect(analyzeMeal(t0, after, [], { now }).flags).toContain("no_baseline");
    const r = analyzeMeal(t0, pts.filter((p) => p.ts <= t0 + 60 * MIN), [], { now: t0 + 60 * MIN });
    expect(r.flags).toContain("incomplete");
  });

  test("no data", () => {
    const r = analyzeMeal(t0, [], [], { now });
    expect(r.flags).toContain("no_data");
    expect(r.peak).toBeNull();
  });
});

describe("LLU client against mock", () => {
  test("region redirect, token reuse, account-id", async () => {
    const c = new LluClient({ email: "a@b.c", password: "x", fetch: createMockFetch(), hostFor: mockHostFor });
    const conns = await c.connections();
    expect(conns.length).toBe(1);
    expect(c.currentRegion).toBe("mock");
    const g = await c.graph(conns[0]!.patientId);
    expect(g.graphData.length).toBeGreaterThan(100);
    expect(itemToReading(g.graphData[0], "graph")).not.toBeNull();
    expect(c.loginCount).toBe(2); // global + regional, then cached
    await c.logbook(conns[0]!.patientId);
    expect(c.loginCount).toBe(2);
  });

  test("bad password is a fatal auth error", async () => {
    const c = new LluClient({ email: "a@b.c", password: "wrong", fetch: createMockFetch(), hostFor: mockHostFor });
    const e = await c.connections().catch((x) => x);
    expect(e).toBeInstanceOf(LluError);
    expect(e.kind).toBe("auth");
    expect(e.fatal).toBe(true);
  });

  test("missing credentials", async () => {
    const c = new LluClient({ email: "", password: "" });
    expect((await c.connections().catch((x) => x)).kind).toBe("config");
  });

  test("poller stores readings; empty connections stops it", async () => {
    const store = new Store(openDb(":memory:"));
    const quiet = () => {};
    const c = new LluClient({ email: "a", password: "b", fetch: createMockFetch(), hostFor: mockHostFor });
    const p = new Poller(c, store, { intervalMin: 5, log: quiet });
    await p.pollNow();
    p.stop();
    expect(p.status.state).toBe("ok");
    expect(store.readingStats().count).toBeGreaterThan(140);

    const c2 = new LluClient({ email: "a", password: "b", fetch: createMockFetch({ connections: false }), hostFor: mockHostFor });
    const p2 = new Poller(c2, new Store(openDb(":memory:")), { intervalMin: 5, log: quiet });
    await p2.pollNow();
    expect(p2.status.state).toBe("stopped");
    expect(p2.status.errorKind).toBe("no_connections");
  });

  test("CSV rows near API rows are skipped", () => {
    const store = new Store(openDb(":memory:"));
    const t = Date.UTC(2026, 10, 24, 0, 0);
    store.upsertReadings([{ ts: t, mgdl: 100, source: "graph", trend: 3 }]);
    const r = store.insertCsvReadings([
      { ts: t + 3 * MIN, mgdl: 101, source: "csv", trend: null },
      { ts: t + 30 * MIN, mgdl: 110, source: "csv", trend: null },
    ]);
    expect(r).toEqual({ inserted: 1, skipped: 1 });
  });
});
