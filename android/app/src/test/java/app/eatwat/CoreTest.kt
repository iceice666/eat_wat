private fun utc(y: Int, mo: Int, d: Int, h: Int, mi: Int, s: Int = 0) =
    LocalDateTime.of(y, mo, d, h, mi, s).toInstant(ZoneOffset.UTC).toEpochMilli()

private val TAIPEI = ZoneId.of("Asia/Taipei")

class TimeTest {
    @Test fun usTwelveHourUtc() {
        assertEquals(utc(2026, 11, 24, 10, 5), parseLluTimestamp("11/24/2026 10:05:00 AM"))
        assertEquals(utc(2026, 11, 24, 0, 5), parseLluTimestamp("11/24/2026 12:05:00 AM"))
        assertEquals(utc(2026, 11, 24, 12, 5), parseLluTimestamp("11/24/2026 12:05:00 PM"))
        assertEquals(utc(2026, 1, 2, 15, 4, 5), parseLluTimestamp("1/2/2026 3:04:05 PM"))
        // Shape seen from the live API (FactoryTimestamp UTC vs Timestamp local +8).
        assertEquals(utc(2026, 11, 24, 11, 2, 52), parseLluTimestamp("11/24/2026 11:02:52 AM"))
    }

    @Test fun isoAndEpoch() {
        assertEquals(utc(2026, 11, 24, 10, 5), parseLluTimestamp("2026-11-24T18:05:00+08:00"))
        assertEquals(utc(2026, 11, 24, 10, 5), parseLluTimestamp("2026-11-24 10:05:00"))
        assertEquals(1_795_000_000_000L, parseLluTimestamp(1_795_000_000L))
        assertNull(parseLluTimestamp("yesterday"))
        assertNull(parseLluTimestamp(null))
    }

    @Test fun localOrderDetection() {
        val dmy = listOf(splitLocalTimestamp("24-11-2026 22:05")!!, splitLocalTimestamp("03-11-2026 08:00")!!)
        assertEquals(DateOrder.DMY, detectDateOrder(dmy))
        assertEquals(DateOrder.MDY, detectDateOrder(listOf(splitLocalTimestamp("11-24-2026 10:05 PM")!!)))
        val p = splitLocalTimestamp("2026/11/24 下午 10:05")!!
        assertEquals(DateOrder.YMD, detectDateOrder(listOf(p)))
        assertEquals(utc(2026, 11, 24, 14, 5), partsToEpoch(p, DateOrder.YMD, TAIPEI))
    }
}

private const val META = "Glucose Data,Generated on,11-24-2026 09:00 UTC,Generated by,Someone\n"

class CsvTest {
    @Test fun mgdlMdy() {
        val csv = META +
            "Device,Serial Number,Device Timestamp,Record Type,Historic Glucose mg/dL,Scan Glucose mg/dL,Notes\n" +
            "FreeStyle LibreLink,ABC,11-24-2026 08:00 AM,0,100,,\n" +
            "FreeStyle LibreLink,ABC,11-24-2026 08:15 AM,0,120,,\n" +
            "FreeStyle LibreLink,ABC,11-24-2026 08:20 AM,1,,130,\n" +
            "FreeStyle LibreLink,ABC,11-24-2026 08:30 AM,6,,,\"note, with comma\"\n"
        val r = parseLibreViewCsv(csv, TAIPEI)
        assertEquals("mg/dL", r.unit)
        assertEquals(DateOrder.MDY, r.dateOrder)
        assertEquals(listOf(100.0, 120.0, 130.0), r.readings.map { it.mgdl })
        assertEquals(utc(2026, 11, 24, 0, 0), r.readings[0].ts)
        assertEquals(1, r.rowsSkipped)
    }

    @Test fun mmolDmyReordered() {
        val csv = META +
            "Device,Serial Number,Record Type,Device Timestamp,Scan Glucose mmol/L,Historic Glucose mmol/L\n" +
            "X,1,0,25-11-2026 07:00,,5.5\r\nX,1,0,25-11-2026 07:15,,7.0\r\n"
        val r = parseLibreViewCsv(csv, ZoneOffset.UTC)
        assertEquals("mmol/L", r.unit)
        assertEquals(DateOrder.DMY, r.dateOrder)
        assertEquals(listOf(99.1, 126.1), r.readings.map { it.mgdl })
        assertEquals(utc(2026, 11, 25, 7, 0), r.readings[0].ts)
    }
}

class AnalysisTest {
    private val t0 = utc(2026, 11, 24, 4, 0)
    private val now = t0 + 24 * HOUR_MS
    private val curve = listOf(100, 100, 100, 130, 155, 160, 140, 120, 105, 100, 98, 98, 99, 100, 100)
    private val pts = curve.mapIndexed { i, v -> Point(t0 + (i - 2) * 15 * MIN_MS, v.toDouble()) }

    @Test fun cleanResponse() {
        val r = analyzeMeal(t0, pts, now = now)
        assertEquals(100.0, r.baseline!!, 0.0)
        assertEquals(160.0, r.peak!!, 0.0)
        assertEquals(45, r.minutesToPeak)
        assertEquals(60.0, r.delta!!, 0.0)
        assertEquals(98.0, r.at2h!!, 0.0)
        assertEquals(90, r.minutesToReturn)
        assertTrue(r.flags.isEmpty())
        assertFalse(r.lowConfidence)
        assertEquals((15 + 42.5 + 57.5 + 50 + 30 + 12.5 + 2.5) * 0.25, r.iauc!!, 0.1)
    }

    @Test fun gapOverlapPrior() {
        val gappy = pts.filter { it.ts < t0 + 30 * MIN_MS || it.ts > t0 + 90 * MIN_MS }
        assertTrue(Flag.GAP in analyzeMeal(t0, gappy, now = now).flags)
        val ov = analyzeMeal(t0, pts, listOf(t0, t0 + 60 * MIN_MS), now = now)
        assertTrue(Flag.OVERLAP in ov.flags && ov.lowConfidence)
        assertTrue(Flag.PRIOR_MEAL in analyzeMeal(t0, pts, listOf(t0 - 60 * MIN_MS), now = now).flags)
        assertFalse(Flag.PRIOR_MEAL in analyzeMeal(t0, pts, listOf(t0 - 4 * HOUR_MS), now = now).flags)
    }

    @Test fun noBaselineIncompleteNoData() {
        assertTrue(Flag.NO_BASELINE in analyzeMeal(t0, pts.filter { it.ts > t0 + 20 * MIN_MS }, now = now).flags)
        assertTrue(Flag.INCOMPLETE in analyzeMeal(t0, pts.filter { it.ts <= t0 + 60 * MIN_MS }, now = t0 + 60 * MIN_MS).flags)
        val empty = analyzeMeal(t0, emptyList(), now = now)
        assertTrue(Flag.NO_DATA in empty.flags)
        assertNull(empty.peak)
    }
}

class LluTest {
    private fun client(pw: String = "x", t: MockTransport = MockTransport(), store: SessionStore = MemorySessionStore()) =
        LluClient("a@b.c", pw, t, store, hostFor = ::mockHostFor)

    @Test fun redirectAndTokenReuse() {
        val c = client()
        val conns = c.connections()
        assertEquals(1, conns.size)
        assertEquals(MOCK_REGION, c.region)
        val g = c.graph(conns[0].patientId)!!
        val items = g.getJSONArray("graphData")
        assertTrue(items.length() >= 47)
        assertNotNull(itemToReading(items.getJSONObject(0), "graph"))
        assertNull(itemToReading(items.getJSONObject(0), "graph")!!.trend) // graph items carry no TrendArrow
        assertEquals(2, c.loginCount) // global + regional
        c.logbook(conns[0].patientId)
        assertEquals(2, c.loginCount)
    }

    @Test fun persistedSessionMeansNoLogin() {
        val store = MemorySessionStore()
        client(store = store).connections()
        val second = client(store = store) // e.g. a new WorkManager process
        second.connections()
        assertEquals(0, second.loginCount)
        assertEquals(MOCK_REGION, second.region)
    }

    @Test fun badPasswordIsFatalAuth() {
        val e = runCatching { client("wrong").connections() }.exceptionOrNull() as LluException
        assertEquals(LluErrorKind.AUTH, e.kind)
        assertTrue(e.kind.fatal)
    }

    @Test fun stepWithTicketIsNotALogin() {
        val store = MemorySessionStore()
        val e = runCatching { client("needs-tou", store = store).connections() }.exceptionOrNull() as LluException
        assertEquals(LluErrorKind.STEP, e.kind)
        assertNull(store.session)
    }

    @Test fun missingCredentials() {
        val e = runCatching { LluClient("", "", MockTransport(), MemorySessionStore()).connections() }.exceptionOrNull() as LluException
        assertEquals(LluErrorKind.CONFIG, e.kind)
    }

    @Test fun syncWritesAndChecksClock() {
        val got = mutableListOf<Reading>()
        val r = runSync(client(), { got += it; it.size })
        assertTrue(r.ok)
        assertTrue(got.size >= 48)
        assertNull(r.timeWarning)
        assertNotNull(JSONObject(r.rawSample!!).optString("FactoryTimestamp"))

        val skewed = LluClient("a", "b", MockTransport(now = { System.currentTimeMillis() - 8 * HOUR_MS }), MemorySessionStore(), hostFor = ::mockHostFor,
            clock = { System.currentTimeMillis() - 8 * HOUR_MS })
        assertTrue(runSync(skewed, { it.size }).timeWarning!!.contains("8 小時"))
    }

    @Test fun noConnectionsIsFatal() {
        val c = LluClient("a", "b", MockTransport(withConnections = false), MemorySessionStore(), hostFor = ::mockHostFor)
        val r = runSync(c, { it.size })
        assertFalse(r.ok)
        assertEquals(LluErrorKind.NO_CONNECTIONS, r.errorKind)
    }

    @Test fun clockSkew() {
        val now = utc(2026, 11, 24, 10, 0)
        assertNull(checkClockSkew(now - 3 * MIN_MS, now))
        assertNull(checkClockSkew(now - 95 * MIN_MS, now))
        assertTrue(checkClockSkew(now + 8 * HOUR_MS, now)!!.contains("比現在晚"))
    }
}
